/**
 * Register both dictionaries into the shell locale service.
 * A deployment without the locale service keeps rendering keys instead of
 * failing this plugin's apply.
 * @param ctx client context (service: locale, optional).
 * @returns disposer removing the dictionaries.
 */
function registerLocales(ctx) {
  let locale
  try {
    locale = ctx === undefined || ctx === null ? undefined : ctx.locale
  } catch {
    locale = undefined
  }
  if (locale === undefined || typeof locale.register !== 'function') return function () {}
  try {
    const dispose = locale.register(NS, { zh: zh, en: en })
    return function () {
      try {
        dispose()
      } catch {
        /* already gone */
      }
    }
  } catch {
    return function () {}
  }
}

