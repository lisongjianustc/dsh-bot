#!/usr/bin/env node
/**
 * Build the browser half of dsh-bot into lib/client.js.
 *
 * The host recognises only a built bundle shaped as
 * `window.__ModuleLoader__.load({ id, factory })`. This script keeps the
 * source as small CommonJS files under src/client/ and emits that wrapper:
 * every source file becomes one lazy module inside the factory closure, so
 * `require('./x.js')` resolves inside the bundle and `require('react')`
 * falls through to the host module table.
 *
 * Usage: node scripts/build-client.mjs
 */
import { execFileSync } from 'node:child_process'
import { mkdirSync, readdirSync, readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = dirname(dirname(fileURLToPath(import.meta.url)))
const srcDir = join(root, 'src', 'client')
const outFile = join(root, 'lib', 'client.js')
const PACKAGE_ID = '@lisongjianustc/dsh-bot'

const files = readdirSync(srcDir).filter((name) => name.endsWith('.js')).sort()
if (!files.includes('index.js')) {
  console.error('build-client: src/client/index.js is missing')
  process.exit(1)
}

let modules = ''
for (const name of files) {
  const body = readFileSync(join(srcDir, name), 'utf8')
  modules += `__modules[${JSON.stringify('./' + name)}] = function (module, exports, require) {\n${body}\n};\n`
}

const out = `/* generated by scripts/build-client.mjs — edit src/client/*.js instead */
window.__ModuleLoader__.load({
  id: ${JSON.stringify(PACKAGE_ID)},
  factory(require) {
    'use strict'
    const __modules = Object.create(null)
    const __cache = Object.create(null)
    function __localRequire(request) {
      if (!request.startsWith('.')) return require(request)
      const cached = __cache[request]
      if (cached) return cached.exports
      const factory = __modules[request]
      if (factory === undefined) throw new Error('dsh-bot client: unknown module ' + request)
      const module = { exports: {} }
      __cache[request] = module
      factory(module, module.exports, __localRequire)
      return module.exports
    }
${modules}
    return __localRequire('./index.js')
  },
})
`

mkdirSync(dirname(outFile), { recursive: true })
writeFileSync(outFile, out)
execFileSync(process.execPath, ['--check', outFile], { stdio: 'inherit' })
const bytes = Buffer.byteLength(out)
console.log(`build-client: ${files.length} modules -> lib/client.js (${bytes} bytes)`)
